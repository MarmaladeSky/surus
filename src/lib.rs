/// A bound parameter value in PostgreSQL text format, with its type name.
#[derive(Debug, Clone, PartialEq)]
pub struct Arg {
    pub ty: String,
    pub value: Option<String>,
}

/// Conversion of a Rust value into the text format of the PostgreSQL type `T`.
pub trait ToPg<T: PgType> {
    fn to_pg(&self) -> Option<String>;
}

macro_rules! to_pg {
    ($($v:ty => $t:ident)*) => {$(
        impl ToPg<types::$t> for $v {
            fn to_pg(&self) -> Option<String> {
                Some(self.to_string())
            }
        }
    )*};
}

to_pg! {
    bool => Bool
    i16 => Int2
    i32 => Int4
    i64 => Int8
    f32 => Float4
    f64 => Float8
    &str => Text
    String => Text
    &str => Varchar
    String => Varchar
}

impl<T: PgType, V: ToPg<T> + ?Sized> ToPg<T> for &V {
    fn to_pg(&self) -> Option<String> {
        (**self).to_pg()
    }
}

impl<T: PgType<Null = types::NotNull>, V: ToPg<T>> ToPg<Nullable<T>> for Option<V> {
    fn to_pg(&self) -> Option<String> {
        self.as_ref().and_then(ToPg::to_pg)
    }
}

impl<T: Element, V: ToPg<T>> ToPg<Array<T>> for [V] {
    fn to_pg(&self) -> Option<String> {
        let items: Vec<String> = self
            .iter()
            .map(|item| match item.to_pg() {
                Some(text) => format!("\"{}\"", text.replace('\\', "\\\\").replace('"', "\\\"")),
                None => "NULL".to_string(),
            })
            .collect();
        Some(format!("{{{}}}", items.join(",")))
    }
}

impl<T: Element, V: ToPg<T>> ToPg<Array<T>> for Vec<V> {
    fn to_pg(&self) -> Option<String> {
        self.as_slice().to_pg()
    }
}

/// The declared parameters of a query, a tuple of SQL types.
pub trait Params {
    /// One `Param` handle per parameter.
    type Handles;
    const LEN: usize;
    fn handles() -> Self::Handles;
}

/// Rust values for the parameters `P`.
pub trait Bind<P> {
    fn args(self) -> Vec<Arg>;
}

/// The row type of a query, a tuple of SQL types.
pub trait Row {
    /// The row's columns when the query is a FROM item.
    type Columns: Source;
    const LEN: usize;
    fn types() -> Vec<String>;
    #[doc(hidden)]
    fn columns_by(rel: &dyn Fn(usize) -> ast::Rel) -> Self::Columns;

    #[doc(hidden)]
    fn columns(alias: Alias) -> Self::Columns {
        Self::columns_by(&|_| alias.0)
    }

    #[doc(hidden)]
    fn outputs() -> Self::Columns {
        Self::columns_by(&ast::Rel::Output)
    }

    #[doc(hidden)]
    fn keys(id: u64) -> Self::Columns {
        Self::columns_by(&|index| ast::Rel::Key(id, index))
    }
}

/// A compiled statement: SQL text, the values of its parameters, the types
/// `P` of the parameters still to bind and the row type `R`.
pub struct Query<P, R> {
    sql: String,
    args: Vec<Arg>,
    types: PhantomData<fn(P) -> R>,
}

impl<P, R> Query<P, R> {
    /// Wraps already rendered SQL; queries are normally compiled from the DSL.
    pub fn new(sql: String, args: Vec<Arg>) -> Query<P, R> {
        Query {
            sql,
            args,
            types: PhantomData,
        }
    }
}

impl<P: Params, R> Query<P, R> {
    pub fn bind(self, values: impl Bind<P>) -> Query<(), R> {
        let mut args = values.args();
        args.extend(self.args);
        Query::new(self.sql, args)
    }
}

impl<R> Query<(), R> {
    pub fn sql(&self) -> &str {
        &self.sql
    }

    pub fn args(&self) -> &[Arg] {
        &self.args
    }
}

/// Compiles a statement with declared parameters, which the closure receives
/// as `Param` handles: `query(|(name,)| users.filter(|u| u.name.eq(name)))`.
pub fn query<P: Params, R, Q: Rows>(statement: impl FnOnce(P::Handles) -> Q) -> Query<P, R>
where
    Q::Row: types::SameType<R>,
{
    compile(statement(P::handles()), P::LEN)
}

fn compile<P, R, Q: Rows>(statement: Q, params: usize) -> Query<P, R> {
    let (sql, args) = render::render(&statement.into_statement(), params);
    Query::new(sql, args)
}

/// Compiles a statement without parameters, with rows of type `R`.
impl<Q: Rows, R> From<Q> for Query<(), R>
where
    Q::Row: types::SameType<R>,
{
    fn from(statement: Q) -> Self {
        compile(statement, 0)
    }
}
