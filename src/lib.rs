//! A statically typed embedded DSL for PostgreSQL queries.
//!
//! Queries are built from typed schema definitions, represented as a query
//! tree whose types are checked by the Rust compiler, and rendered into SQL
//! with bound parameters:
//!
//! ```text
//! users.filter(|u| u.name.eq(name)).select(|u| (u.id, u.email))
//!     → SELECT t1."id", t1."email" FROM "public"."users" AS t1 WHERE (t1."name" = $1)
//! ```
//!
//! Each FROM item is handed to the closures of the query, so a column can
//! only be referenced through the query that has it in scope, and columns on
//! the nullable side of an outer join have nullable types.
//!
//! The layers, from catalog to SQL:
//!
//! - `types`: PostgreSQL types as markers, with the casts between them;
//!   `ops`: operators as traits implemented for their operand types. Both
//!   are generated from `pg_type`, `pg_cast` and `pg_operator` by
//!   `cargo run -p opgen`.
//! - The typed schema of a database, generated by
//!   `cargo run -p schemagen -- <output.rs> [fixture.sql ...]`: a struct per
//!   table and view, enums, domains, composite types and constraints.
//! - The DSL: `Select`, `Insert`, `Update`, `Delete`, `Merge`, expressions and
//!   functions, which check types and build an untyped query tree.
//! - The renderer, which serializes the tree into a [`Query`]: SQL text, the
//!   values of its parameters, and its parameter and row types. Executing it
//!   is left to a PostgreSQL driver.

